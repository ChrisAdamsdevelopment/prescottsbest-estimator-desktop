import assert from 'node:assert/strict';
import { build } from 'esbuild';
await build({entryPoints:['src/projectModel.ts'],outfile:'tests/.project.bundle.mjs',bundle:true,platform:'node',format:'esm',logLevel:'silent'});
const { landedQuoteCost, quoteIsComparable, compareSupplierQuotes, scheduleForecast, projectCommercial, rfqDraft } = await import('./.project.bundle.mjs');
const s = { id:'s1', name:'Pella custom window', category:'windows', spec:'123 approved exact dimensions', manufacturer:'Pella', model:'Custom X', quantity:2, unit:'ea', allowanceCost:7000, chosenQuoteId:'q1', approvedByCustomer:true};
const q1={id:'q1',selectionId:'s1',supplier:'Vendor A',supplierRef:'R123',status:'confirmed',exactSpec:true,unitCost:2000,quantity:2,shipping:500,taxAndFees:100,leadDays:14,validUntil:'',notes:''};
const q2={...q1,id:'q2',supplier:'Vendor B',unitCost:1900,shipping:400,leadDays:21};
const qWrong={...q1,id:'wrong',supplier:'Vendor C',exactSpec:false,unitCost:50};
assert.equal(landedQuoteCost(q1),4600);
assert.equal(landedQuoteCost(q2),4300);
assert.equal(quoteIsComparable(s,qWrong),false);
assert.equal(compareSupplierQuotes(s,[q1,q2,qWrong]).cheapest.id,'q2');
assert.equal(compareSupplierQuotes(s,[q1,q2,qWrong]).savings,300);
assert.equal(compareSupplierQuotes(s,[{...q2,validUntil:'2025-01-01'}]).ranked.length,0);
const job={items:[{id:'a',category:'labor',qty:2,unit:'h',unitCost:50}],addOns:[],contract:{mode:'cost_plus',feeBasis:'percent',feePercent:20,fixedFee:0,note:''},selections:[s],supplierQuotes:[q1],workPhases:[{id:'p1',name:'Prep',personHours:32,crewSize:2,hoursPerDay:8,loadedCostPerHour:45,blockingSelectionId:'',extraDays:0},{id:'p2',name:'Install',personHours:16,crewSize:2,hoursPerDay:8,loadedCostPerHour:45,blockingSelectionId:'s1',extraDays:0}],actualExpenses:[{id:'act',amount:50,category:'Materials',reference:'A',date:'2026-11-01',description:'paid'}],margin:50,contingency:10,overheadAllowance:20,minimumCharge:0,discount:0,taxRate:0};
const base={direct:100,contingencyCost:10,overhead:20,afterDiscount:260};
const financials=projectCommercial(job,base);
assert.equal(financials.total,132);
assert.equal(financials.projectedFee,22);
assert.equal(financials.projectedProfit,2);
assert.equal(financials.actualDirectCosts,50);
assert.equal(financials.billableActualsIllustration,60);
const fixed=projectCommercial({...job,contract:{...job.contract,mode:'fixed'}},base);
assert.equal(fixed.total,260);
const scheduled=scheduleForecast(job);
assert.equal(scheduled.totalPersonHours,48);
assert.equal(scheduled.plannedLaborCost,2160);
assert.equal(scheduled.totalWorkDays,15);
assert.equal(scheduled.entries[1].waitDays,12);
assert.ok(rfqDraft(s,'Customer','Address').includes('No order is authorized'));
console.log('PASS: dual pricing model, quote comparison on landed exact-spec prices, expiry check, supplier lead-time scheduling, labor cost and recorded actuals.');
